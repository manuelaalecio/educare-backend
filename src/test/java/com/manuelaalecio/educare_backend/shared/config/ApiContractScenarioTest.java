package com.manuelaalecio.educare_backend.shared.config;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import com.jayway.jsonpath.DocumentContext;
import com.jayway.jsonpath.JsonPath;
import com.manuelaalecio.educare_backend.shared.testsupport.TestcontainersConfiguration;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.server.LocalServerPort;
import org.springframework.context.annotation.Import;
import org.springframework.test.context.TestPropertySource;

/**
 * Scenarios of the requirements "Contrato versionado igual à API" and "Contrato sem dados de ambiente nem dados
 * pessoais" (spec api-contract). The document is generated by the application itself, on a real HTTP server in a
 * random port, and compared with the committed {@code openapi/educare-api.json}; with
 * {@code -Deducare.apiContract.update=true} ({@code ./gradlew updateApiContract}) the file is rewritten instead. The
 * failure scenarios use a temporary file, never the committed one.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@Import(TestcontainersConfiguration.class)
@TestPropertySource(properties = "springdoc.api-docs.enabled=true")
class ApiContractScenarioTest {

	@LocalServerPort
	private int port;

	@Value("${educare.security.jwt.secret}")
	private String jwtSecret;

	@TempDir
	private Path tempDir;

	@Test
	@DisplayName("Scenario: Contrato em dia")
	void shouldMatchCommittedContractWhenApiIsUnchanged() {
		// given
		String generated = generate();
		if (ApiContract.isUpdateMode()) {
			ApiContract.write(ApiContract.CONTRACT_FILE, generated);
		}

		// when / then
		ApiContract.verify(ApiContract.CONTRACT_FILE, generated);
	}

	@Test
	@DisplayName("Scenario: Contrato ausente")
	void shouldFailWithUpdateCommandWhenContractFileIsMissing() {
		// given
		Path missing = tempDir.resolve("educare-api.json");

		// when / then
		assertThatThrownBy(() -> ApiContract.verify(missing, generate()))
			.isInstanceOf(AssertionError.class)
			.hasMessageContaining("./gradlew updateApiContract");
	}

	@Test
	@DisplayName("Scenario: Endpoint alterado sem atualizar o contrato")
	void shouldFailWithUpdateCommandWhenResponseGainsFieldMissingFromContract() {
		// given: the committed contract predates the field login of MeResponse
		String generated = generate();
		DocumentContext outdated = JsonPath.parse(generated)
			.delete("$.components.schemas.MeResponse.properties.login");
		Path file = tempDir.resolve("educare-api.json");
		ApiContract.write(file, ApiContract.normalize(outdated.jsonString()));

		// when / then
		assertThatThrownBy(() -> ApiContract.verify(file, generated))
			.isInstanceOf(AssertionError.class)
			.hasMessageContaining("./gradlew updateApiContract");
	}

	@Test
	@DisplayName("Scenario: Contrato regenerado")
	void shouldPassVerificationWhenOutdatedContractIsRewritten() {
		// given
		Path file = tempDir.resolve("educare-api.json");
		ApiContract.write(file, "{}\n");
		String generated = generate();

		// when
		ApiContract.write(file, generated);

		// then
		ApiContract.verify(file, generated);
	}

	@Test
	@DisplayName("Scenario: Geração determinística")
	void shouldGenerateIdenticalContractWithRelativeServerWhenGeneratedTwice() {
		// when
		String first = generate();
		String second = generate();

		// then
		assertThat(second).isEqualTo(first);
		List<Map<String, Object>> servers = JsonPath.read(first, "$.servers");
		assertThat(servers).containsExactly(Map.of("url", "/"));
	}

	@Test
	@DisplayName("Scenario: Contrato sem endereço de ambiente")
	void shouldNotContainHostNorPortWhenServerRunsOnRandomPort() {
		// when
		String generated = generate();

		// then
		assertThat(generated).doesNotContain("localhost", "127.0.0.1", String.valueOf(port));
	}

	@Test
	@DisplayName("Scenario: Contrato sem segredo")
	void shouldNotContainSigningKeyWhenDevKeyIsConfigured() {
		// when
		String generated = generate();

		// then
		assertThat(jwtSecret).isNotBlank();
		assertThat(generated).doesNotContain(jwtSecret);
	}

	@Test
	@DisplayName("Scenario: Corpo de erro real atende ao schema")
	void shouldReturnEveryRequiredProblemDetailFieldWhenLoginHasInvalidCredentials() {
		// given
		List<String> required = JsonPath.read(generate(), "$.components.schemas.ProblemDetail.required");
		HttpRequest request = HttpRequest.newBuilder(URI.create("http://localhost:" + port + "/api/v1/auth/login"))
			.header("Content-Type", "application/json")
			.POST(HttpRequest.BodyPublishers.ofString("""
					{"login": "ninguem@educare.org", "password": "senha-errada"}"""))
			.build();

		// when
		HttpResponse<String> response = send(request);

		// then
		assertThat(response.statusCode()).isEqualTo(401);
		assertThat(response.headers().firstValue("Content-Type")).hasValue("application/problem+json");
		Map<String, Object> body = JsonPath.read(response.body(), "$");
		assertThat(required).isNotEmpty();
		assertThat(body).containsKeys(required.toArray(String[]::new));
	}

	private String generate() {
		HttpRequest request = HttpRequest.newBuilder(URI.create("http://localhost:" + port + "/v3/api-docs")).build();
		HttpResponse<String> response = send(request);
		assertThat(response.statusCode()).isEqualTo(200);
		return ApiContract.normalize(response.body());
	}

	private static HttpResponse<String> send(HttpRequest request) {
		try (HttpClient client = HttpClient.newHttpClient()) {
			return client.send(request, HttpResponse.BodyHandlers.ofString());
		}
		catch (IOException ex) {
			throw new IllegalStateException(ex);
		}
		catch (InterruptedException ex) {
			Thread.currentThread().interrupt();
			throw new IllegalStateException(ex);
		}
	}

}
