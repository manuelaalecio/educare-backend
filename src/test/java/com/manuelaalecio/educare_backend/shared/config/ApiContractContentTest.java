	@Test
	@DisplayName("Scenario: Resposta do login")
	void shouldDeclareRequiredTokenFieldsAndNoSecurityWhenReadingLogin() {
		// when
		Map<String, Object> schema = successSchema("/api/v1/auth/login", "post", "200");
		List<Object> security = contract.read("$.paths['/api/v1/auth/login'].post.security");

		// then
		assertThat(required(schema)).contains("accessToken", "tokenType", "expiresIn");
		assertThat(security).isEmpty();
	}

