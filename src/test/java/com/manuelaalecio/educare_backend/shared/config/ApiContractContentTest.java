package com.manuelaalecio.educare_backend.shared.config;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.InstanceOfAssertFactories.MAP;

import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

import com.jayway.jsonpath.DocumentContext;
import com.jayway.jsonpath.JsonPath;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

/**
 * Scenarios of the requirements "Respostas de sucesso com campos obrigatórios declarados" and "Respostas de erro
 * descritas como ProblemDetail" (spec api-contract), read from the committed {@code openapi/educare-api.json}. The
 * {@link ApiContractScenarioTest} guarantees that the file is the document generated by the application.
 */
class ApiContractContentTest {

	private static final String SCHEMA_REF_PREFIX = "#/components/schemas/";

	private static final String PROBLEM_DETAIL_REF = SCHEMA_REF_PREFIX + "ProblemDetail";

	private static DocumentContext contract;

	@BeforeAll
	static void readContract() {
		contract = JsonPath.parse(ApiContract.read(ApiContract.CONTRACT_FILE));
	}

	@Test
	@DisplayName("Scenario: Resposta do login")
	void shouldDeclareRequiredTokenFieldsAndNoSecurityWhenReadingLogin() {
		// when
		Map<String, Object> schema = successSchema("/api/v1/auth/login", "post", "200");
		List<Object> security = contract.read("$.paths['/api/v1/auth/login'].post.security");

		// then
		assertThat(required(schema)).contains("accessToken", "tokenType", "expiresIn");
		assertThat(security).isEmpty();
	}

	@Test
	@DisplayName("Scenario: Resposta dos próprios dados")
	void shouldDeclareRequiredUserFieldsWithoutPasswordWhenReadingMe() {
		// when
		Map<String, Object> schema = successSchema("/api/v1/auth/me", "get", "200");

		// then
		assertThat(required(schema)).contains("id", "name", "login", "role", "createdAt", "updatedAt");
		assertThat(properties(schema)).doesNotContainKey("password");
	}

	@ParameterizedTest
	@CsvSource({"/api/v1/auth/me/password, put", "/api/v1/users/{id}/password, put", "/api/v1/users/{id}, delete"})
	@DisplayName("Scenario: Operação sem corpo de resposta")
	void shouldDeclareNoContentWithoutBodyWhenOperationReturnsNothing(String path, String method) {
		// when
		Map<String, Object> responses = responses(path, method);

		// then
		assertThat(responses).containsKey("204").doesNotContainKeys("200");
		assertThat(response(path, method, "204")).doesNotContainKey("content");
	}

	@Test
	@DisplayName("Scenario: Criação com Location")
	void shouldDeclareCreatedWithLocationAndUserSchemaWhenReadingUserCreation() {
		// when
		Map<String, Object> created = response("/api/v1/users", "post", "201");
		Map<String, Object> schema = successSchema("/api/v1/users", "post", "201");

		// then
		assertThat(responses("/api/v1/users", "post")).doesNotContainKey("200");
		assertThat(created).extractingByKey("headers").asInstanceOf(MAP).containsKey("Location");
		assertThat(required(schema)).contains("id", "name", "login", "role", "createdAt", "updatedAt");
	}

	@ParameterizedTest
	@CsvSource({"/api/v1/users/{id}, get", "/api/v1/users/{id}, put"})
	void shouldDeclareRequiredUserFieldsWhenOperationReturnsOneUser(String path, String method) {
		// when
		Map<String, Object> schema = successSchema(path, method, "200");

		// then
		assertThat(required(schema)).contains("id", "name", "login", "role", "createdAt", "updatedAt");
	}

	@Test
	@DisplayName("Scenario: Nenhuma resposta com media type genérico")
	void shouldNotDeclareWildcardMediaTypeWhenReadingAnyResponse() {
		// when
		List<Map<String, Object>> contents = contract.read("$.paths.*.*.responses.*.content");

		// then
		assertThat(contents).isNotEmpty().allSatisfy(content -> assertThat(content).doesNotContainKey("*/*"));
	}

	@Test
	void shouldDeclareRequiredPageFieldsWhenReadingUserListing() {
		// when
		Map<String, Object> schema = successSchema("/api/v1/users", "get", "200");

		// then
		assertThat(required(schema)).contains("content", "page");
	}

	@Test
	void shouldNotExposePasswordNorAuthorshipWhenReadingResponseSchemas() {
		// given
		Set<String> requestSchemas = new HashSet<>(
				contract.<List<String>>read("$.paths.*.*.requestBody.content.*.schema.$ref").stream()
					.map(ref -> ref.substring(SCHEMA_REF_PREFIX.length()))
					.toList());
		Map<String, Map<String, Object>> schemas = contract.read("$.components.schemas");

		// when / then
		assertThat(schemas.keySet()).contains("UserResponse", "MeResponse", "AccessTokenResponse");
		schemas.forEach((name, schema) -> {
			if (!requestSchemas.contains(name)) {
				assertThat(properties(schema)).as(name).doesNotContainKeys("password", "createdBy", "updatedBy");
			}
		});
	}

	@Test
	@DisplayName("Scenario: Schema de ProblemDetail com erros de campo")
	void shouldDeclareOptionalFieldErrorsWhenReadingProblemDetailSchema() {
		// when
		Map<String, Object> problemDetail = contract.read("$.components.schemas.ProblemDetail");
		String itemsRef = contract.read("$.components.schemas.ProblemDetail.properties.errors.items.$ref");
		Map<String, Object> fieldError = schema(itemsRef);

		// then
		assertThat(properties(problemDetail)).containsKeys("type", "title", "status", "detail", "instance", "errors");
		assertThat(required(problemDetail)).containsExactlyInAnyOrder("title", "status");
		assertThat(required(fieldError)).containsExactlyInAnyOrder("field", "message");
	}

	@Test
	@DisplayName("Scenario: Erros do login")
	void shouldDeclareBadRequestAndUnauthorizedProblemsWhenReadingLogin() {
		// when / then
		assertProblemResponses("/api/v1/auth/login", "post", "400", "401");
	}

	@Test
	@DisplayName("Scenario: Erros de uma operação de ADMIN")
	void shouldDeclareAdminOperationProblemsWhenReadingUserCreation() {
		// when / then
		assertProblemResponses("/api/v1/users", "post", "400", "401", "403", "409");
	}

	@ParameterizedTest
	@CsvSource({"/api/v1/users, get", "/api/v1/users/{id}, get", "/api/v1/users/{id}, put",
			"/api/v1/users/{id}/password, put", "/api/v1/users/{id}, delete"})
	void shouldDeclareUnauthorizedAndForbiddenWhenOperationRequiresAdmin(String path, String method) {
		// when / then
		assertProblemResponses(path, method, "401", "403");
	}

	@ParameterizedTest
	@CsvSource({"/api/v1/users/{id}, get", "/api/v1/users/{id}, put", "/api/v1/users/{id}/password, put",
			"/api/v1/users/{id}, delete"})
	void shouldDeclareBadRequestAndNotFoundWhenOperationLooksUpUserById(String path, String method) {
		// when / then
		assertProblemResponses(path, method, "400", "404");
	}

	@Test
	@DisplayName("Scenario: Operação de qualquer usuário autenticado não declara 403")
	void shouldDeclareUnauthorizedWithoutForbiddenWhenReadingMe() {
		// when / then
		assertProblemResponses("/api/v1/auth/me", "get", "401");
		assertThat(responses("/api/v1/auth/me", "get")).doesNotContainKey("403");
	}

	private static void assertProblemResponses(String path, String method, String... statuses) {
		for (String status : statuses) {
			String ref = contract.read(operationPath(path, method) + ".responses['" + status
					+ "'].content['application/problem+json'].schema.$ref");
			assertThat(ref).as("%s %s %s", method, path, status).isEqualTo(PROBLEM_DETAIL_REF);
		}
	}

	private static Map<String, Object> responses(String path, String method) {
		return contract.read(operationPath(path, method) + ".responses");
	}

	private static Map<String, Object> response(String path, String method, String status) {
		return contract.read(operationPath(path, method) + ".responses['" + status + "']");
	}

	/** The schema of the {@code application/json} body of a success response, with its reference resolved. */
	private static Map<String, Object> successSchema(String path, String method, String status) {
		String ref = contract.read(operationPath(path, method) + ".responses['" + status
				+ "'].content['application/json'].schema.$ref");
		return schema(ref);
	}

	private static Map<String, Object> schema(String ref) {
		assertThat(ref).startsWith(SCHEMA_REF_PREFIX);
		return contract.read("$.components.schemas['" + ref.substring(SCHEMA_REF_PREFIX.length()) + "']");
	}

	private static String operationPath(String path, String method) {
		return "$.paths['" + path + "']." + method;
	}

	@SuppressWarnings("unchecked")
	private static List<String> required(Map<String, Object> schema) {
		return (List<String>) schema.getOrDefault("required", List.of());
	}

	@SuppressWarnings("unchecked")
	private static Map<String, Object> properties(Map<String, Object> schema) {
		return (Map<String, Object>) schema.getOrDefault("properties", Map.of());
	}

}
